#!/usr/bin/env node
// Generates every review's own page, reviews/<slug>/index.html, the link
// manifest reviews/index.json, and sitemap.xml.
//
// waxReviews.html is the template: for each live set the <title>/description/
// canonical/social tags (between its review-head markers) and the globals
// script (between its review-params markers) are swapped for that set's own
// values, so crawlers that don't run JavaScript get a per-set preview. The
// page's JS still renders the review itself.
//
// Amplify runs this on every build (amplify.yml), and a change to a live set
// in the CMS starts a build (Lambdas/cardsRebuildTrigger), so none of the
// output is committed. Nothing is written unless every live set has a valid,
// unique seoURLSlug and both templates' markers are found exactly once.
//
// Runs on Node 16 (the Amplify build image), hence node:https, not fetch.
// Each set's pageName comes from categoryRanges in scripts/helper.js.
//
// Usage: node generate.mjs (writes ../../reviews/ and ../../sitemap.xml).

import fs from "node:fs";
import https from "node:https";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const SITE_ORIGIN = "https://www.junkwaxhockey.com";
const SETS_URL = "https://jlpd8ec14j.execute-api.us-east-2.amazonaws.com/prod";
const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const REVIEWS_DIR = path.join(REPO_ROOT, "reviews");
const TEMPLATE_PATH = path.join(REPO_ROOT, "waxReviews.html");
const HELPER_PATH = path.join(REPO_ROOT, "scripts", "helper.js");
const DEFAULT_IMAGE = "https://s3.us-east-2.amazonaws.com/mellowjohnny.cc.files/img/hellaFilesArch.webp";
const BANNER = "<!-- Generated by tools/generateReviewPages from waxReviews.html - do not edit; re-run the generator. -->";
const SLUG_PATTERN = /^[a-z0-9]+(-[a-z0-9]+)*$/;

// waxReviews.html redirects exactly this year+category to lockout.html
// (the 2004-05 season was cancelled), so it never gets a review page.
const REDIRECTED_COMBOS = new Set(["2004|mcd"]);

const STATIC_PAGES = [
  "/",
  "/playerSearch.html",
  "/lockout.html",
  "/theJunkWaxYears.html",
  "/timeline.html",
  "/browseBySet.html",
  "/about.html"
];

function getJson(url) {
  return new Promise((resolve, reject) => {
    https.get(url, (res) => {
      let body = "";
      res.setEncoding("utf8");
      res.on("data", (chunk) => { body += chunk; });
      res.on("end", () => {
        if (res.statusCode !== 200) return reject(new Error(`${url} answered ${res.statusCode}`));
        try { resolve(JSON.parse(body)); } catch { reject(new Error(`${url} did not return JSON`)); }
      });
    }).on("error", reject);
  });
}

// A dropped or throttled request shouldn't fail a build: three tries, then give up.
async function fetchLiveSets() {
  let lastError;
  for (let attempt = 1; attempt <= 3; attempt++) {
    try {
      const sets = await getJson(SETS_URL);
      if (!Array.isArray(sets) || sets.length === 0) throw new Error("The sets endpoint returned no sets");
      if (!sets.some((set) => set.stars !== undefined)) {
        throw new Error("The sets endpoint does not return stars - redeploy Lambdas/getPublicCardSets");
      }
      return sets;
    } catch (err) {
      lastError = err;
      if (attempt < 3) await new Promise((resolve) => setTimeout(resolve, 2000));
    }
  }
  throw lastError;
}

// categoryRanges is a plain object literal in scripts/helper.js (a browser
// script, not a Node module), so lift it out of the source text.
function loadCategoryRanges() {
  const match = fs.readFileSync(HELPER_PATH, "utf8").match(/const categoryRanges = (\{[\s\S]*?\n\});/);
  if (!match) throw new Error("Could not find the categoryRanges object in scripts/helper.js");
  const ranges = new Function(`return ${match[1]}`)();
  if (!ranges || Object.keys(ranges).length === 0) throw new Error("categoryRanges in scripts/helper.js is empty");
  return ranges;
}

function pageNameFor(set, categoryRanges) {
  const pages = Object.values(categoryRanges[set.blogCat] || {});
  const range = pages.find((r) => set.year >= r.start && set.year <= r.end);
  if (!range) throw new Error(`No year range covers "${set.setName}" (${set.blogCat} ${set.year}) - extend categoryRanges in scripts/helper.js`);
  return range.pageName;
}

// The sets that get a page, each checked for the fields a page can't do without.
function reviewSets(sets) {
  const live = sets.filter((set) => !REDIRECTED_COMBOS.has(`${set.year}|${set.blogCat}`));
  const problems = [];
  const seen = new Map();
  for (const set of live) {
    if (!set.setID || !set.setName || !Number.isFinite(set.year)) throw new Error(`Unusable set record: ${JSON.stringify(set)}`);
    const slug = typeof set.seoURLSlug === "string" ? set.seoURLSlug.trim() : "";
    if (!slug) problems.push(`"${set.setName}" has no SEO Friendly URL`);
    else if (!SLUG_PATTERN.test(slug)) problems.push(`"${set.setName}" has an invalid slug "${slug}"`);
    else if (seen.has(slug)) problems.push(`"${set.setName}" and "${seen.get(slug)}" share the slug "${slug}"`);
    else seen.set(slug, set.setName);
  }
  if (problems.length) throw new Error(`Fix these in the CMS first:\n  - ${problems.join("\n  - ")}`);
  return live.map((set) => ({ ...set, seoURLSlug: set.seoURLSlug.trim() }));
}

function escapeAttr(text) {
  return String(text).replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

// The text between two marker comments, replaced; each marker must occur once.
function replaceBetween(html, name, replacement) {
  const start = `<!-- ${name}:start -->`;
  const end = `<!-- ${name}:end -->`;
  if (html.split(start).length !== 2 || html.split(end).length !== 2) {
    throw new Error(`waxReviews.html must contain "${start}" and "${end}" exactly once each`);
  }
  const from = html.indexOf(start);
  const to = html.indexOf(end) + end.length;
  if (to < from) throw new Error(`${name} markers are out of order in waxReviews.html`);
  return html.slice(0, from) + replacement + html.slice(to);
}

// Mirrors the title/description/image fallbacks in fetchPageTitle() (scripts/wax.js),
// except the description: the review text isn't in the public list.
function headBlock(set, url, warnings) {
  const title = (set.seoPageTitle || "").trim() || `${set.setName} Hockey Card Set Review`;
  let description = (set.seoMetaDesc || "").trim();
  if (!description) {
    description = `${set.setName} hockey card set review from Junk Wax Hockey.`;
    warnings.push(`"${set.setName}" has no SEO Meta Description - used a generic one`);
  }
  const image = set.headerImg && set.headerImgName ? `${set.headerImg}${set.headerImgName}` : DEFAULT_IMAGE;
  const keywords = (set.seoTags || "").trim();
  const lines = [
    `<title>${escapeAttr(title)}</title>`,
    `<meta name="description" content="${escapeAttr(description)}">`,
    ...(keywords ? [`<meta name="keywords" content="${escapeAttr(keywords)}">`] : []),
    `<link rel="canonical" href="${url}">`,
    `<meta property="og:type" content="website">`,
    `<meta property="og:url" content="${url}">`,
    `<meta property="og:title" content="${escapeAttr(title)}">`,
    `<meta property="og:description" content="${escapeAttr(description)}">`,
    `<meta property="og:image" content="${escapeAttr(image)}">`,
    `<meta name="twitter:card" content="summary_large_image">`,
    `<meta name="twitter:title" content="${escapeAttr(title)}">`,
    `<meta name="twitter:description" content="${escapeAttr(description)}">`,
    `<meta name="twitter:image" content="${escapeAttr(image)}">`
  ];
  return lines.join("\n    ");
}

function paramsBlock(set, categoryRanges) {
  return `<script>
      const params = new URLSearchParams(window.location.search);
      const year = ${JSON.stringify(String(set.year))};
      const sortOrder = params.get("sortOrder");
      const pageName = ${JSON.stringify(pageNameFor(set, categoryRanges))};
      const blogCat = ${JSON.stringify(set.blogCat)};
      const setID = ${JSON.stringify(set.setID)};
    </script>`;
}

function buildPage(template, set, categoryRanges, warnings) {
  const url = `${SITE_ORIGIN}/reviews/${set.seoURLSlug}/`;
  let html = replaceBetween(template, "review-head", headBlock(set, url, warnings));
  html = replaceBetween(html, "review-params", paramsBlock(set, categoryRanges));
  const doctypeEnd = html.indexOf(">") + 1;
  if (!/^<!doctype html>/i.test(html)) throw new Error("waxReviews.html must start with <!doctype html>");
  return `${html.slice(0, doctypeEnd)}\n${BANNER}${html.slice(doctypeEnd)}`;
}

// <lastmod> for a review: the date it was last edited (updatedAt, written by
// updateCardSet) or, for sets never edited since, its publish date (now).
function setLastmod(set) {
  const stamp = set.updatedAt || set.now;
  return stamp && /^\d{4}-\d{2}-\d{2}/.test(stamp) ? stamp.slice(0, 10) : undefined;
}

// A static page's last commit date; undefined when git has no history for it.
function pageLastmod(page) {
  const file = page === "/" ? "index.html" : page.slice(1);
  try {
    const date = execFileSync("git", ["log", "-1", "--format=%cs", "--", file], { cwd: REPO_ROOT, encoding: "utf8" }).trim();
    return date || undefined;
  } catch {
    return undefined;
  }
}

function buildUrls(sets) {
  const urls = STATIC_PAGES.map((page) => ({ loc: `${SITE_ORIGIN}${page}`, lastmod: pageLastmod(page) }));
  const ordered = [...sets].sort((a, b) =>
    a.blogCat.localeCompare(b.blogCat) || a.year - b.year || a.setName.localeCompare(b.setName));
  for (const set of ordered) urls.push({ loc: `${SITE_ORIGIN}/reviews/${set.seoURLSlug}/`, lastmod: setLastmod(set) });
  return urls;
}

function buildSitemapXml(urls) {
  const entries = urls.map(({ loc, lastmod }) =>
    `  <url>\n    <loc>${loc}</loc>\n${lastmod ? `    <lastmod>${lastmod}</lastmod>\n` : ""}  </url>`).join("\n");
  return `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${entries}\n</urlset>\n`;
}

function writeIfChanged(file, content) {
  if (fs.existsSync(file) && fs.readFileSync(file, "utf8") === content) return false;
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
  return true;
}

// What the nav, year picker and Player Search read to link to the pages built
// here (see loadReviewLinks() in scripts/helper.js): only sets that have a page.
function buildManifest(sets) {
  const ordered = [...sets].sort((a, b) =>
    a.blogCat.localeCompare(b.blogCat) || a.year - b.year || a.setName.localeCompare(b.setName));
  return JSON.stringify(ordered.map(({ setID, setName, blogCat, year, seoURLSlug, stars }) =>
    ({ setID, setName, blogCat, year, seoURLSlug, stars }))) + "\n";
}

try {
  const sets = reviewSets(await fetchLiveSets());
  const template = fs.readFileSync(TEMPLATE_PATH, "utf8");
  const categoryRanges = loadCategoryRanges();
  const warnings = [];
  const pages = sets.map((set) => ({ set, html: buildPage(template, set, categoryRanges, warnings) }));
  const urls = buildUrls(sets);

  let written = 0;
  for (const { set, html } of pages) {
    if (writeIfChanged(path.join(REVIEWS_DIR, set.seoURLSlug, "index.html"), html)) written++;
  }
  writeIfChanged(path.join(REVIEWS_DIR, "index.json"), buildManifest(sets));
  writeIfChanged(path.join(REPO_ROOT, "sitemap.xml"), buildSitemapXml(urls));

  warnings.forEach((warning) => console.warn(`warning: ${warning}`));
  console.log(`${sets.length} review pages (${written} written), the link manifest and ${urls.length} sitemap URLs.`);
} catch (err) {
  console.error(`Nothing changed: ${err.message}`);
  process.exit(1);
}
