#!/usr/bin/env node
// Generates every review's own page, reviews/<slug>/index.html, the link
// manifest reviews/index.json, and sitemap.xml.
//
// waxReviews.html is the template: for each live set the <title>/description/
// canonical/social tags (between its review-head markers) and the globals
// script (between its review-params markers) are swapped for that set's own
// values, so crawlers that don't run JavaScript get a per-set preview. The year
// picker (set-picker markers) is pre-rendered with /reviews/<slug>/ links too.
// The page's JS still renders the review itself.
//
// Amplify runs this on every build (amplify.yml), and a change to a live set
// in the CMS starts a build (Lambdas/cardsRebuildTrigger), so none of the
// output is committed. Nothing is written unless every live set has a valid,
// unique seoURLSlug and both templates' markers are found exactly once.
//
// It also pre-renders, so the HTML itself links to every /reviews/<slug>/ page:
// the main nav and footer (nav and footer markers) into each review page and into
// the static pages in NAV_PAGE_FILES, and the browse-major / browse-fastfood columns into
// browseBySet.html (browseColumnHtml() in scripts/browseBySet.js). Those static
// pages are tracked, so a local run leaves them modified: discard the changes.
//
// Runs on Node 16 (the Amplify build image), hence node:https, not fetch.
// Each set's pageName comes from categoryRanges in scripts/helper.js.
//
// Usage: node generate.mjs (writes ../../reviews/ and ../../sitemap.xml).

import fs from "node:fs";
import https from "node:https";
import path from "node:path";
import vm from "node:vm";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const SITE_ORIGIN = "https://www.junkwaxhockey.com";
const SETS_URL = "https://jlpd8ec14j.execute-api.us-east-2.amazonaws.com/prod";
const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const REVIEWS_DIR = path.join(REPO_ROOT, "reviews");
const TEMPLATE_PATH = path.join(REPO_ROOT, "waxReviews.html");
const HELPER_PATH = path.join(REPO_ROOT, "scripts", "helper.js");
const WAX_PATH = path.join(REPO_ROOT, "scripts", "wax.js");
const BROWSE_PAGE_PATH = path.join(REPO_ROOT, "browseBySet.html");
const BROWSE_SCRIPT_PATH = path.join(REPO_ROOT, "scripts", "browseBySet.js");
const WAX_MUSEUM_SCRIPT_PATH = path.join(REPO_ROOT, "scripts", "waxMuseum.js");
// The set-data endpoint fetchCardSetsByYear() calls in scripts/wax.js; the preload below must use
// the identical URL or the browser fetches it twice.
const SETS_BY_YEAR_URL = "https://a92dwyl3ic.execute-api.us-east-2.amazonaws.com/dev";
const DEFAULT_IMAGE ="https://s3.us-east-2.amazonaws.com/mellowjohnny.cc.files/img/hellaFilesArch.webp";
const BANNER = "<!-- Generated by tools/generateReviewPages from waxReviews.html - do not edit; re-run the generator. -->";
const SLUG_PATTERN = /^[a-z0-9]+(-[a-z0-9]+)*$/;

// waxReviews.html redirects exactly this year+category to lockout.html
// (the 2004-05 season was cancelled), so it never gets a review page.
const REDIRECTED_COMBOS = new Set(["2004|mcd"]);

const STATIC_PAGES = [
  "/",
  "/playerSearch.html",
  "/lockout.html",
  "/theJunkWaxYears.html",
  "/timeline.html",
  "/browseBySet.html",
  "/waxMuseum.html",
  "/about.html"
];

function getJson(url) {
  return new Promise((resolve, reject) => {
    https.get(url, (res) => {
      let body = "";
      res.setEncoding("utf8");
      res.on("data", (chunk) => { body += chunk; });
      res.on("end", () => {
        if (res.statusCode !== 200) return reject(new Error(`${url} answered ${res.statusCode}`));
        try { resolve(JSON.parse(body)); } catch { reject(new Error(`${url} did not return JSON`)); }
      });
    }).on("error", reject);
  });
}

// A dropped or throttled request shouldn't fail a build: three tries, then give up.
async function fetchLiveSets() {
  let lastError;
  for (let attempt = 1; attempt <= 3; attempt++) {
    try {
      const sets = await getJson(SETS_URL);
      if (!Array.isArray(sets) || sets.length === 0) throw new Error("The sets endpoint returned no sets");
      if (!sets.some((set) => set.stars !== undefined)) {
        throw new Error("The sets endpoint does not return stars - redeploy Lambdas/getPublicCardSets");
      }
      return sets;
    } catch (err) {
      lastError = err;
      if (attempt < 3) await new Promise((resolve) => setTimeout(resolve, 2000));
    }
  }
  throw lastError;
}

// The Wax Museum's phone LCP is its first pack's front image, which the page only names after fetching the
// pack list. This writes a preload for it into waxMuseum.html, using the page's own sort and URL from
// scripts/waxMuseum.js. Optional: any failure leaves the marker empty with a warning, never fails the build.
async function waxLcpPreload(page, warnings) {
  try {
    const context = {};
    vm.createContext(context);
    const museum = vm.runInContext(`${fs.readFileSync(WAX_MUSEUM_SCRIPT_PATH, "utf8")}
      ;({ sortWaxPacks, WAX_PACK_IMAGE_BASE, WAX_PACK_GET_URL })`, context);
    const fetchPreload = page.match(/<link rel="preload" as="fetch" crossorigin href="([^"]+)">/);
    if (!fetchPreload || fetchPreload[1] !== museum.WAX_PACK_GET_URL) {
      warnings.push("waxMuseum.html's pack-list preload doesn't match WAX_PACK_GET_URL in scripts/waxMuseum.js");
    }
    const packs = await getJson(museum.WAX_PACK_GET_URL);
    const first = Array.isArray(packs) ? museum.sortWaxPacks(packs)[0] : null;
    if (!first || !first.frontImg) throw new Error("no first pack with a front image");
    const href = museum.WAX_PACK_IMAGE_BASE + encodeURIComponent(first.frontImg);
    return `<link rel="preload" as="image" href="${escapeAttr(href)}" fetchpriority="high">`;
  } catch (err) {
    warnings.push(`Wax Museum LCP preload left out: ${err.message}`);
    return "";
  }
}

// categoryRanges is a plain object literal in scripts/helper.js (a browser
// script, not a Node module), so lift it out of the source text.
function loadCategoryRanges() {
  const match = fs.readFileSync(HELPER_PATH, "utf8").match(/const categoryRanges = (\{[\s\S]*?\n\});/);
  if (!match) throw new Error("Could not find the categoryRanges object in scripts/helper.js");
  const ranges = new Function(`return ${match[1]}`)();
  if (!ranges || Object.keys(ranges).length === 0) throw new Error("categoryRanges in scripts/helper.js is empty");
  return ranges;
}

function pageNameFor(set, categoryRanges) {
  const pages = Object.values(categoryRanges[set.blogCat] || {});
  const range = pages.find((r) => set.year >= r.start && set.year <= r.end);
  if (!range) throw new Error(`No year range covers "${set.setName}" (${set.blogCat} ${set.year}) - extend categoryRanges in scripts/helper.js`);
  return range.pageName;
}

// The sets that get a page, each checked for the fields a page can't do without.
function reviewSets(sets) {
  const live = sets.filter((set) => !REDIRECTED_COMBOS.has(`${set.year}|${set.blogCat}`));
  const problems = [];
  const seen = new Map();
  for (const set of live) {
    if (!set.setID || !set.setName || !Number.isFinite(set.year)) throw new Error(`Unusable set record: ${JSON.stringify(set)}`);
    const slug = typeof set.seoURLSlug === "string" ? set.seoURLSlug.trim() : "";
    if (!slug) problems.push(`"${set.setName}" has no SEO Friendly URL`);
    else if (!SLUG_PATTERN.test(slug)) problems.push(`"${set.setName}" has an invalid slug "${slug}"`);
    else if (seen.has(slug)) problems.push(`"${set.setName}" and "${seen.get(slug)}" share the slug "${slug}"`);
    else seen.set(slug, set.setName);
  }
  if (problems.length) throw new Error(`Fix these in the CMS first:\n  - ${problems.join("\n  - ")}`);
  return live.map((set) => ({ ...set, seoURLSlug: set.seoURLSlug.trim() }));
}

function escapeAttr(text) {
  return String(text).replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

// The text between two marker comments, replaced; each marker must occur once.
// keepMarkers leaves the comments in place around the replacement.
function replaceBetween(html, name, replacement, file = "waxReviews.html", keepMarkers = false) {
  const start = `<!-- ${name}:start -->`;
  const end = `<!-- ${name}:end -->`;
  if (html.split(start).length !== 2 || html.split(end).length !== 2) {
    throw new Error(`${file} must contain "${start}" and "${end}" exactly once each`);
  }
  const from = html.indexOf(start);
  const to = html.indexOf(end) + end.length;
  if (to < from) throw new Error(`${name} markers are out of order in ${file}`);
  return keepMarkers
    ? html.slice(0, from + start.length) + replacement + html.slice(to - end.length)
    : html.slice(0, from) + replacement + html.slice(to);
}

// The source text of a top-level function in a browser script, by name.
function liftFunction(source, name, file) {
  const match = source.match(new RegExp(`^function ${name}\\([\\s\\S]*?\\n\\}`, "m"));
  if (!match) throw new Error(`Could not find function ${name}() in ${file}`);
  return match[0];
}

// The text between two marker lines (// name:start ... // name:end) in a browser script.
function liftBlock(source, name, file) {
  const start = source.indexOf(`// ${name}:start`);
  const end = source.indexOf(`// ${name}:end`);
  if (start < 0 || end < start) throw new Error(`Could not find the "${name}" block in ${file}`);
  return source.slice(start, end);
}

// The browser functions the pages are pre-rendered with (browseColumnHtml() in
// scripts/browseBySet.js; setPickerHtml(), compareSetsForDefault() and navHtml()
// in scripts/helper.js), run in a sandbox with the few helpers they call.
function loadBrowserFunctions(categoryRanges) {
  const helperSource = fs.readFileSync(HELPER_PATH, "utf8");
  const waxSource = fs.readFileSync(WAX_PATH, "utf8");
  const context = {
    categoryRanges,
    SITE_ORIGIN,
    setJsonLd: () => {}
  };
  vm.createContext(context);
  vm.runInContext([
    liftFunction(helperSource, "escapeHtml", "scripts/helper.js"),
    liftFunction(helperSource, "getPageNameForYear", "scripts/helper.js"),
    liftFunction(helperSource, "setPickerHtml", "scripts/helper.js"),
    liftFunction(helperSource, "compareSetsForDefault", "scripts/helper.js"),
    liftFunction(helperSource, "reviewLinkAttrs", "scripts/helper.js"),
    liftBlock(helperSource, "nav-block", "scripts/helper.js"),
    liftBlock(helperSource, "footer-block", "scripts/helper.js"),
    liftFunction(waxSource, "stripYearFromSetName", "scripts/wax.js"),
    fs.readFileSync(BROWSE_SCRIPT_PATH, "utf8")
  ].join("\n"), context);
  for (const name of ["browseColumnHtml", "setPickerHtml", "compareSetsForDefault", "navHtml", "footerHtml"]) {
    if (typeof context[name] !== "function") throw new Error(`${name}() did not load from the browser scripts`);
  }
  return context;
}

// A year picker's link for each year: the page of that year's default set (the
// one applyReviewLinks() picks), or nothing for a year with no review page.
function pickerHrefFor(set, sets, compareSetsForDefault) {
  return (year) => {
    const best = sets.filter((s) => s.blogCat === set.blogCat && s.year === year).sort(compareSetsForDefault)[0];
    return best ? `/reviews/${best.seoURLSlug}/` : null;
  };
}

// A nav link's final href: the page of the default set for the item's category
// and year (what applyReviewLinks() picks), or nothing for an item that isn't a set link.
function navHrefFor(sets, compareSetsForDefault) {
  return (item) => {
    if (!item.review) return null;
    const best = sets.filter((s) => s.blogCat === item.review.cat && s.year === item.review.year).sort(compareSetsForDefault)[0];
    return best ? `/reviews/${best.seoURLSlug}/` : null;
  };
}

// The pages with a nav pre-rendered into them, besides the review pages. Each
// names its NAV_MAP key in data-nav-page on #global-nav.
const NAV_PAGE_FILES = [
  "index.html", "about.html", "playerSearch.html", "timeline.html", "theJunkWaxYears.html",
  "browseBySet.html", "waxMuseum.html", "lockout.html"
];

// html with its nav and footer markers filled (navHtml(pageName, ...), footerHtml(...)).
function fillNav(html, pageName, navMarkup, footerMarkup, file) {
  if (!navMarkup) throw new Error(`${file}: "${pageName}" has no NAV_MAP entry in scripts/helper.js`);
  return replaceBetween(replaceBetween(html, "nav", navMarkup, file, true), "footer", footerMarkup, file, true);
}

// browseBySet.html with both columns filled in. The same filters as initBrowseBySet().
function buildBrowsePage(sets, browseColumnHtml) {
  const live = sets.filter((set) => set.setName && Number.isFinite(set.year));
  const page = fs.readFileSync(BROWSE_PAGE_PATH, "utf8");
  const major = browseColumnHtml(live.filter((set) => set.blogCat === "reg"));
  const fastFood = browseColumnHtml(live.filter((set) => set.blogCat === "mcd" || set.blogCat === "tims"));
  const withMajor = replaceBetween(page, "browse-major", major, "browseBySet.html", true);
  return replaceBetween(withMajor, "browse-fastfood", fastFood, "browseBySet.html", true);
}

// Mirrors the title/description/image fallbacks in fetchPageTitle() (scripts/wax.js),
// except the description: the review text isn't in the public list.
function headBlock(set, url, warnings) {
  const title = (set.seoPageTitle || "").trim() || `${set.setName} Hockey Card Set Review`;
  let description = (set.seoMetaDesc || "").trim();
  if (!description) {
    description = `${set.setName} hockey card set review from Junk Wax Hockey.`;
    warnings.push(`"${set.setName}" has no SEO Meta Description - used a generic one`);
  }
  const image = set.headerImg && set.headerImgName ? `${set.headerImg}${set.headerImgName}` : DEFAULT_IMAGE;
  const keywords = (set.seoTags || "").trim();
  const hasHeaderImage = set.headerImg && set.headerImgName;
  const lines = [
    `<title>${escapeAttr(title)}</title>`,
    `<meta name="description" content="${escapeAttr(description)}">`,
    ...(keywords ? [`<meta name="keywords" content="${escapeAttr(keywords)}">`] : []),
    `<link rel="canonical" href="${url}">`,
    `<meta property="og:type" content="website">`,
    `<meta property="og:url" content="${url}">`,
    `<meta property="og:title" content="${escapeAttr(title)}">`,
    `<meta property="og:description" content="${escapeAttr(description)}">`,
    `<meta property="og:image" content="${escapeAttr(image)}">`,
    `<meta name="twitter:card" content="summary_large_image">`,
    `<meta name="twitter:title" content="${escapeAttr(title)}">`,
    `<meta name="twitter:description" content="${escapeAttr(description)}">`,
    `<meta name="twitter:image" content="${escapeAttr(image)}">`,
    // The header image is the page's LCP, but wax.js only adds its <img> after the data
    // fetch; this lets the download start with the HTML. No crossorigin, to match the <img>.
    ...(hasHeaderImage ? [`<link rel="preload" as="image" href="${escapeAttr(image)}" fetchpriority="high">`] : []),
    // Starts the set-data request with the HTML instead of after the deferred scripts have
    // loaded; wax.js's plain fetch() of the same URL picks it up. crossorigin = CORS fetch.
    `<link rel="preload" as="fetch" crossorigin href="${escapeAttr(`${SETS_BY_YEAR_URL}?year=${set.year}&blogCat=${set.blogCat}`)}">`
  ];
  return lines.join("\n    ");
}

function paramsBlock(set, categoryRanges) {
  return `<script>
      const params = new URLSearchParams(window.location.search);
      const year = ${JSON.stringify(String(set.year))};
      const sortOrder = params.get("sortOrder");
      const pageName = ${JSON.stringify(pageNameFor(set, categoryRanges))};
      const blogCat = ${JSON.stringify(set.blogCat)};
      const setID = ${JSON.stringify(set.setID)};
    </script>`;
}

function buildPage(template, set, categoryRanges, warnings, pickerHtml, navMarkup, footerMarkup) {
  const url = `${SITE_ORIGIN}/reviews/${set.seoURLSlug}/`;
  let html = replaceBetween(template, "review-head", headBlock(set, url, warnings));
  html = replaceBetween(html, "review-params", paramsBlock(set, categoryRanges));
  html = replaceBetween(html, "set-picker", pickerHtml, "waxReviews.html", true);
  html = fillNav(html, pageNameFor(set, categoryRanges), navMarkup, footerMarkup, "waxReviews.html");
  // The set name as the raw HTML's H1, for crawlers that don't run JavaScript (wax.js swaps in the visible one).
  const emptyH1 = '<h1 id="pageHeader"></h1>';
  if (html.split(emptyH1).length !== 2) throw new Error(`waxReviews.html must contain "${emptyH1}" exactly once`);
  html = html.replace(emptyH1, `<h1 id="pageHeader">${escapeAttr(set.setName)}</h1>`);
  const doctypeEnd = html.indexOf(">") + 1;
  if (!/^<!doctype html>/i.test(html)) throw new Error("waxReviews.html must start with <!doctype html>");
  return `${html.slice(0, doctypeEnd)}\n${BANNER}${html.slice(doctypeEnd)}`;
}

// <lastmod> for a review: the date it was last edited (updatedAt, written by
// updateCardSet) or, for sets never edited since, its publish date (now).
function setLastmod(set) {
  const stamp = set.updatedAt || set.now;
  return stamp && /^\d{4}-\d{2}-\d{2}/.test(stamp) ? stamp.slice(0, 10) : undefined;
}

// A static page's last commit date; undefined when git has no history for it.
function pageLastmod(page) {
  const file = page === "/" ? "index.html" : page.slice(1);
  try {
    const date = execFileSync("git", ["log", "-1", "--format=%cs", "--", file], { cwd: REPO_ROOT, encoding: "utf8" }).trim();
    return date || undefined;
  } catch {
    return undefined;
  }
}

function buildUrls(sets) {
  const urls = STATIC_PAGES.map((page) => ({ loc: `${SITE_ORIGIN}${page}`, lastmod: pageLastmod(page) }));
  const ordered = [...sets].sort((a, b) =>
    a.blogCat.localeCompare(b.blogCat) || a.year - b.year || a.setName.localeCompare(b.setName));
  for (const set of ordered) urls.push({ loc: `${SITE_ORIGIN}/reviews/${set.seoURLSlug}/`, lastmod: setLastmod(set) });
  return urls;
}

function buildSitemapXml(urls) {
  const entries = urls.map(({ loc, lastmod }) =>
    `  <url>\n    <loc>${loc}</loc>\n${lastmod ? `    <lastmod>${lastmod}</lastmod>\n` : ""}  </url>`).join("\n");
  return `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${entries}\n</urlset>\n`;
}

function writeIfChanged(file, content) {
  if (fs.existsSync(file) && fs.readFileSync(file, "utf8") === content) return false;
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
  return true;
}

// What the nav, year picker and Player Search read to link to the pages built
// here (see loadReviewLinks() in scripts/helper.js): only sets that have a page.
function buildManifest(sets) {
  const ordered = [...sets].sort((a, b) =>
    a.blogCat.localeCompare(b.blogCat) || a.year - b.year || a.setName.localeCompare(b.setName));
  return JSON.stringify(ordered.map(({ setID, setName, blogCat, year, seoURLSlug, stars }) =>
    ({ setID, setName, blogCat, year, seoURLSlug, stars }))) + "\n";
}

try {
  const liveSets = await fetchLiveSets();
  const sets = reviewSets(liveSets);
  const template = fs.readFileSync(TEMPLATE_PATH, "utf8");
  const categoryRanges = loadCategoryRanges();
  const warnings = [];
  const { browseColumnHtml, setPickerHtml, compareSetsForDefault, navHtml, footerHtml } = loadBrowserFunctions(categoryRanges);
  const navLinkFor = navHrefFor(sets, compareSetsForDefault);
  const footerMarkup = footerHtml(navLinkFor);
  const pages = sets.map((set) => {
    const pageName = pageNameFor(set, categoryRanges);
    const pickerHtml = setPickerHtml(set.year, set.blogCat, pageName, pickerHrefFor(set, sets, compareSetsForDefault));
    return { set, html: buildPage(template, set, categoryRanges, warnings, pickerHtml, navHtml(pageName, undefined, navLinkFor), footerMarkup) };
  });
  const navPages = await Promise.all(NAV_PAGE_FILES.map(async (file) => {
    let source = file === "browseBySet.html" ? buildBrowsePage(liveSets, browseColumnHtml) : fs.readFileSync(path.join(REPO_ROOT, file), "utf8");
    if (file === "waxMuseum.html") source = replaceBetween(source, "wax-lcp", await waxLcpPreload(source, warnings), file, true);
    const match = source.match(/id="global-nav"[^>]*data-nav-page="([^"]+)"/);
    if (!match) throw new Error(`${file} needs data-nav-page on #global-nav`);
    return { file: path.join(REPO_ROOT, file), html: fillNav(source, match[1], navHtml(match[1], undefined, navLinkFor), footerMarkup, file) };
  }));
  const urls = buildUrls(sets);

  let written = 0;
  for (const { set, html } of pages) {
    if (writeIfChanged(path.join(REVIEWS_DIR, set.seoURLSlug, "index.html"), html)) written++;
  }
  writeIfChanged(path.join(REVIEWS_DIR, "index.json"), buildManifest(sets));
  writeIfChanged(path.join(REPO_ROOT, "sitemap.xml"), buildSitemapXml(urls));
  for (const { file, html } of navPages) writeIfChanged(file, html);

  warnings.forEach((warning) => console.warn(`warning: ${warning}`));
  console.log(`${sets.length} review pages (${written} written), the link manifest and ${urls.length} sitemap URLs.`);
} catch (err) {
  console.error(`Nothing changed: ${err.message}`);
  process.exit(1);
}
